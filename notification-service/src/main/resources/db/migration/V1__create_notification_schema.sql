CREATE TABLE notifications (
    id UUID PRIMARY KEY,
    recipient_user_id VARCHAR(255) NOT NULL,
    recipient_type VARCHAR(24) NOT NULL,
    notification_type VARCHAR(48) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message VARCHAR(5000) NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    read_at TIMESTAMP WITH TIME ZONE,
    correlation_id VARCHAR(100),
    email_recipient VARCHAR(320),
    email_sent BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255)
);

CREATE INDEX idx_notification_recipient
    ON notifications (recipient_user_id, created_at);
CREATE INDEX idx_notification_unread
    ON notifications (recipient_user_id, is_read);

CREATE TABLE revinfo (
    rev INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revtstmp BIGINT NOT NULL,
    user_id VARCHAR(255),
    username VARCHAR(255),
    actor_type VARCHAR(16),
    correlation_id VARCHAR(64)
);

CREATE INDEX idx_notification_rev_user ON revinfo (user_id);
CREATE INDEX idx_notification_rev_timestamp ON revinfo (revtstmp);

CREATE TABLE notifications_aud (
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    id UUID NOT NULL,
    recipient_user_id VARCHAR(255),
    recipient_type VARCHAR(24),
    notification_type VARCHAR(48),
    title VARCHAR(255),
    message VARCHAR(5000),
    is_read BOOLEAN,
    read_at TIMESTAMP WITH TIME ZONE,
    correlation_id VARCHAR(100),
    email_recipient VARCHAR(320),
    email_sent BOOLEAN,
    PRIMARY KEY (rev, id),
    CONSTRAINT fk_notifications_aud_rev
        FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE INDEX idx_notifications_aud_id ON notifications_aud (id);
