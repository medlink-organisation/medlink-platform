CREATE TABLE revinfo (
    rev INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revtstmp BIGINT
);

CREATE TABLE dossiers_medicaux (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    date_creation TIMESTAMP NOT NULL,
    derniere_modification TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT uk_dossiers_medicaux_patient_id UNIQUE (patient_id)
);

CREATE TABLE documents_medicaux (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_medical_id BIGINT NOT NULL,
    nom_fichier VARCHAR(255) NOT NULL,
    type_mime VARCHAR(255) NOT NULL,
    object_key VARCHAR(512) NOT NULL,
    checksum VARCHAR(64) NOT NULL,
    taille_octets BIGINT NOT NULL,
    date_depot TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT uk_documents_medicaux_object_key UNIQUE (object_key),
    CONSTRAINT fk_documents_medicaux_dossier
        FOREIGN KEY (dossier_medical_id) REFERENCES dossiers_medicaux (id)
);

CREATE TABLE resultats_examens (
    id UUID PRIMARY KEY,
    dossier_medical_id BIGINT NOT NULL,
    document_medical_id BIGINT NOT NULL,
    type_examen VARCHAR(150) NOT NULL,
    date_examen DATE NOT NULL,
    conclusion TEXT,
    date_publication TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT uk_resultats_examens_document UNIQUE (document_medical_id),
    CONSTRAINT fk_resultats_examens_dossier
        FOREIGN KEY (dossier_medical_id) REFERENCES dossiers_medicaux (id),
    CONSTRAINT fk_resultats_examens_document
        FOREIGN KEY (document_medical_id) REFERENCES documents_medicaux (id)
);

CREATE TABLE comptes_rendus (
    id UUID PRIMARY KEY,
    dossier_medical_id BIGINT NOT NULL,
    rendez_vous_id UUID NOT NULL,
    praticien_id UUID NOT NULL,
    date_redaction TIMESTAMP NOT NULL,
    contenu TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT uk_comptes_rendus_rendez_vous_id UNIQUE (rendez_vous_id),
    CONSTRAINT fk_comptes_rendus_dossier
        FOREIGN KEY (dossier_medical_id) REFERENCES dossiers_medicaux (id)
);

CREATE INDEX idx_dossiers_medicaux_patient_id
    ON dossiers_medicaux (patient_id);
CREATE INDEX idx_documents_medicaux_dossier_medical_id
    ON documents_medicaux (dossier_medical_id);
CREATE INDEX idx_documents_medicaux_object_key
    ON documents_medicaux (object_key);
CREATE INDEX idx_resultats_examens_dossier_medical_id
    ON resultats_examens (dossier_medical_id);
CREATE INDEX idx_comptes_rendus_dossier_medical_id
    ON comptes_rendus (dossier_medical_id);
CREATE INDEX idx_comptes_rendus_rendez_vous_id
    ON comptes_rendus (rendez_vous_id);
CREATE INDEX idx_comptes_rendus_praticien_id
    ON comptes_rendus (praticien_id);

CREATE TABLE dossiers_medicaux_aud (
    id BIGINT NOT NULL,
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    patient_id BIGINT,
    date_creation TIMESTAMP,
    derniere_modification TIMESTAMP,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_dossiers_medicaux_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE documents_medicaux_aud (
    id BIGINT NOT NULL,
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    dossier_medical_id BIGINT,
    nom_fichier VARCHAR(255),
    type_mime VARCHAR(255),
    object_key VARCHAR(512),
    checksum VARCHAR(64),
    taille_octets BIGINT,
    date_depot TIMESTAMP,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_documents_medicaux_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE resultats_examens_aud (
    id UUID NOT NULL,
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    dossier_medical_id BIGINT,
    document_medical_id BIGINT,
    type_examen VARCHAR(150),
    date_examen DATE,
    conclusion TEXT,
    date_publication TIMESTAMP,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_resultats_examens_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE comptes_rendus_aud (
    id UUID NOT NULL,
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    dossier_medical_id BIGINT,
    rendez_vous_id UUID,
    praticien_id UUID,
    date_redaction TIMESTAMP,
    contenu TEXT,
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_comptes_rendus_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);
