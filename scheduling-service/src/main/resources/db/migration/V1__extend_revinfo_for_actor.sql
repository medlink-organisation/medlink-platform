-- Apply with the scheduling database migration mechanism. Every statement is
-- additive and preserves any revision already stored by Hibernate Envers.
CREATE TABLE IF NOT EXISTS revinfo (
    rev INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revtstmp BIGINT
);

ALTER TABLE revinfo ADD COLUMN IF NOT EXISTS user_id VARCHAR(255);
ALTER TABLE revinfo ADD COLUMN IF NOT EXISTS username VARCHAR(255);
ALTER TABLE revinfo ADD COLUMN IF NOT EXISTS actor_type VARCHAR(16);
ALTER TABLE revinfo ADD COLUMN IF NOT EXISTS correlation_id VARCHAR(64);

CREATE TABLE IF NOT EXISTS creneaux_aud (
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    id BIGINT NOT NULL,
    praticien_id BIGINT,
    clinique_id BIGINT,
    date_debut TIMESTAMP,
    date_fin TIMESTAMP,
    statut VARCHAR(255),
    PRIMARY KEY (rev, id),
    CONSTRAINT fk_creneaux_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE IF NOT EXISTS rendez_vous_aud (
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    id UUID NOT NULL,
    creneau_id BIGINT,
    patient_id BIGINT,
    status VARCHAR(255),
    type VARCHAR(255),
    PRIMARY KEY (rev, id),
    CONSTRAINT fk_rendez_vous_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE INDEX IF NOT EXISTS idx_revinfo_user_id ON revinfo (user_id);
CREATE INDEX IF NOT EXISTS idx_revinfo_revtstmp ON revinfo (revtstmp);
CREATE INDEX IF NOT EXISTS idx_creneaux_aud_id ON creneaux_aud (id);
CREATE INDEX IF NOT EXISTS idx_rendez_vous_aud_id ON rendez_vous_aud (id);
